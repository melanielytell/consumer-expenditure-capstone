#Variance Inflation Factor Check for the Vehicle Insurance Model
import numpy as np
import pandas as pd
import statsmodels.api as sm
import statsmodels.formula.api as smf
from statsmodels.stats.outliers_influence import variance_inflation_factor

formula = """
np.log(AdjVEHINSPQ) ~ HOUSB + AGE_REF + C(CUTENURE)
+ FAM_SIZE + TINCHRS + C(MARITAL1) + C(REF_RACE)
+ SEX_REF + VEHQ + GASMOPQ + VEHFINPQ + MAINRPPQ
+ VRNTLOPQ + PUBTRAPQ + C(STATE) + EVEHPURP
+ HISP_REF + C(HIGH_EDU) + C(QSQ118)
"""

# Build the regression design matrix
model_data = df.copy()
y, X = smf.ols(formula, data=model_data).endog, \
       smf.ols(formula, data=model_data).exog

# Calculate VIF for each design-matrix column
vif = pd.DataFrame({
    'Variable': smf.ols(formula, data=model_data).exog_names,
    'VIF': [
        variance_inflation_factor(X, i)
        for i in range(X.shape[1])
    ]
})

print(vif.sort_values('VIF', ascending=False).to_string(index=False))